-- V008: System and Notification schemas
-- System schema contains global lookups, addresses, and attachments
-- Notification schema contains templates, pushes, and email logs

CREATE SCHEMA IF NOT EXISTS ag_system;
CREATE SCHEMA IF NOT EXISTS ag_notification;

-- ==========================================
-- SYSTEM SCHEMA
-- ==========================================

-- 1. Code Types
CREATE TABLE IF NOT EXISTS ag_system.code_types (
    code_type_id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(25) NOT NULL,
    description VARCHAR(200),
    created_by INTEGER,
    creation_date TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc', now()),
    updated_by INTEGER,
    updation_date TIMESTAMP WITH TIME ZONE
);

-- 2. Codes (Lookups)
CREATE TABLE IF NOT EXISTS ag_system.codes (
    code_id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code_type_id SMALLINT REFERENCES ag_system.code_types(code_type_id),
    parent_id SMALLINT,
    code VARCHAR(200) NOT NULL,
    weightage INTEGER,
    value VARCHAR(200),
    english_name VARCHAR(200),
    hindi_name VARCHAR(200),
    created_by INTEGER,
    creation_date TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc', now()),
    updated_by INTEGER,
    updation_date TIMESTAMP WITH TIME ZONE
);

-- 3. Address
CREATE TABLE IF NOT EXISTS ag_system.address (
    address_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    address_type VARCHAR(20) NOT NULL,
    associated_to VARCHAR(50) NOT NULL,
    associated_id INTEGER NOT NULL,
    address_line1 VARCHAR(150) NOT NULL,
    address_line2 VARCHAR(50),
    suburb VARCHAR(100),
    postcode VARCHAR(10),
    state_id SMALLINT,
    country_id SMALLINT,
    geo_location VARCHAR(70),
    created_by INTEGER,
    creation_date TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc', now()),
    updated_by INTEGER,
    updation_date TIMESTAMP WITH TIME ZONE
);

-- 4. Files
-- Note: ag_system.files might already exist, so we use IF NOT EXISTS 
-- or alter it if needed. For now we assume standard creation.
CREATE TABLE IF NOT EXISTS ag_system.files (
    file_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    file_type VARCHAR(6) NOT NULL,
    associated_to VARCHAR(50) NOT NULL,
    associated_id INTEGER NOT NULL,
    file_path VARCHAR(255) NOT NULL,
    file_name VARCHAR(100),
    extension VARCHAR(10),
    title VARCHAR(150),
    description VARCHAR(150),
    sequence INTEGER,
    created_by INTEGER NOT NULL,
    creation_date TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc', now()) NOT NULL,
    updated_by INTEGER,
    updation_date TIMESTAMP WITH TIME ZONE
);

-- ==========================================
-- NOTIFICATION SCHEMA
-- ==========================================

-- 1. Email Templates / Notifications
CREATE TABLE IF NOT EXISTS ag_notification.email_notifications (
    email_template_id INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    type VARCHAR(100),
    subject VARCHAR(100),
    body TEXT,
    data_fields TEXT,
    created_by INTEGER NOT NULL,
    creation_date TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_by INTEGER,
    updation_date TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

-- 2. Push Notification Template
CREATE TABLE IF NOT EXISTS ag_notification.push_notification_template (
    push_notification_template_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    template_type VARCHAR(250) NOT NULL,
    title TEXT NOT NULL,
    template VARCHAR(255),
    fields VARCHAR(255),
    is_active BOOLEAN DEFAULT true NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc', now()),
    template_code VARCHAR(100) UNIQUE,
    app_route_pattern VARCHAR(255),
    web_route_pattern VARCHAR(255),
    priority_level SMALLINT DEFAULT 1,
    image_url TEXT
);

-- 3. Notifications (Transactional)
CREATE TABLE IF NOT EXISTS ag_notification.notifications (
    notification_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    template_id INTEGER REFERENCES ag_notification.push_notification_template(push_notification_template_id),
    sender_id INTEGER NOT NULL,
    target_scope VARCHAR(50) NOT NULL,
    target_reference_id INTEGER,
    final_title VARCHAR(255) NOT NULL,
    final_body TEXT NOT NULL,
    data_payload JSONB,
    status VARCHAR(20) DEFAULT 'pending',
    priority SMALLINT DEFAULT 1,
    scheduled_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc', now()),
    processed_at TIMESTAMP WITH TIME ZONE,
    total_recipients INTEGER DEFAULT 0,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc', now())
);

-- 4. Notification Recipients
CREATE TABLE IF NOT EXISTS ag_notification.notification_recipients (
    recipient_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    notification_id INTEGER NOT NULL REFERENCES ag_notification.notifications(notification_id) ON DELETE CASCADE,
    user_id INTEGER NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc', now()) NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc', now()) NOT NULL,
    read_at TIMESTAMP WITH TIME ZONE,
    UNIQUE (notification_id, user_id)
);

-- 5. Push Notification Tokens
CREATE TABLE IF NOT EXISTS ag_notification.push_notification_tokens (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL,
    token TEXT NOT NULL,
    auth_key VARCHAR(255),
    p256dh_key VARCHAR(255),
    platform VARCHAR(50) NOT NULL,
    device_type VARCHAR(50),
    is_active BOOLEAN DEFAULT true NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc', now()),
    last_used_at TIMESTAMP WITH TIME ZONE,
    expires_at TIMESTAMP WITH TIME ZONE,
    updated_at TIMESTAMP WITH TIME ZONE,
    device_model VARCHAR(100),
    app_version VARCHAR(20),
    failure_count INTEGER DEFAULT 0,
    last_sync_at TIMESTAMP WITH TIME ZONE,
    UNIQUE (user_id, token, platform)
);

-- 6. Push Notifications Log
CREATE TABLE IF NOT EXISTS ag_notification.push_notifications (
    push_notification_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    notification_id INTEGER NOT NULL,
    push_notification_token_id INTEGER NOT NULL,
    title VARCHAR(255),
    data TEXT,
    status VARCHAR(50) DEFAULT 'pending',
    error_message TEXT,
    delivered_at TIMESTAMP WITH TIME ZONE,
    read_at TIMESTAMP WITH TIME ZONE,
    updated_at TIMESTAMP WITH TIME ZONE,
    retry_count INTEGER DEFAULT 0,
    campaign_id INTEGER REFERENCES ag_notification.notifications(notification_id),
    user_id INTEGER,
    fcm_message_id VARCHAR(255),
    resolved_route VARCHAR(255),
    clicked_at TIMESTAMP WITH TIME ZONE,
    click_count INTEGER DEFAULT 0
);

CREATE INDEX IF NOT EXISTS idx_notif_recipients_notification_id ON ag_notification.notification_recipients(notification_id);
CREATE INDEX IF NOT EXISTS idx_notif_recipients_user_id ON ag_notification.notification_recipients(user_id);
